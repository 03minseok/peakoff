/**
 * 여행 조건. 1단계 화면에서 정하고 이후 모든 단계가 참조한다.
 *
 * 서버의 CourseDiagnosisRequest와 필드 이름을 맞췄다. 진단을 호출할 때
 * 슬롯 목록만 얹으면 그대로 보낼 수 있어, 중간 변환 코드가 필요 없다.
 */
export interface TripPlan {
  /** 지역 슬러그. 예: "gyeongju" */
  region: string
  /** yyyy-MM-dd */
  startDate: string
  /** 박 수 */
  nights: number
}

/**
 * 원안 — 사용자가 직접 짜서 진단에 들고 온 코스.
 *
 * <b>날짜(plan)와 장소(days)를 함께 담는 것이 핵심이다.</b>
 * 장소만 저장하면, 사용자가 더 한적한 날짜로 옮겼을 때 원안까지 새 날짜로 다시 계산된다.
 * 그러면 "날짜를 바꿔서 얼마나 나아졌는지"가 통째로 사라진다.
 *
 * 이렇게 두면 최종 비교가 두 가지 회피 경로를 한 번에 보여준다:
 * 원안(9/12·원래 장소) → 개선안(9/14·교체한 장소).
 */
export interface TripBaseline {
  plan: TripPlan
  days: string[][]
}

/**
 * 여행 흐름 전체가 공유하는 상태.
 *
 * days는 <b>일차별 장소 ID 배열</b>이다. days[0]이 1일차이고, 배열 순서가 곧 방문 순서다.
 *
 * order를 숫자 필드로 따로 들지 않은 이유: 순서를 바꿀 때마다 모든 항목의 order를
 * 다시 매겨야 하고, 그러다 한 번이라도 어긋나면 중복되거나 빈 번호가 생긴다.
 * 배열 위치를 순서로 쓰면 자리를 바꾸는 것만으로 끝난다.
 *
 * 장소 정보 전체가 아니라 ID만 담는 이유: 이름·좌표는 서버가 가진 값이고,
 * 화면을 열 때마다 새로 받는다. 여기에 복사해두면 두 벌이 되어 언젠가 어긋난다.
 */
/**
 * 지금 흐름이 <b>이미 저장된 어느 코스를 고치는 중</b>이라는 표시.
 *
 * 마이페이지의 "수정하기"로 들어왔을 때만 채워지고, 그 밖에는 늘 null이다.
 * 결과 화면이 이것을 보고 새로 저장할지 고쳐 쓸지를 가른다 — 없으면 늘 새 코스가 만들어져
 * 한 번 고칠 때마다 목록에 비슷한 코스가 하나씩 쌓인다.
 *
 * <p>이름과 공개 여부를 함께 들고 오는 이유: 저장 시트가 <b>지금 값</b>을 미리 채워야 한다.
 * 빈 칸으로 두면 이름을 다시 짓게 되고, 공개 토글이 기본값(켜짐)으로 돌아가
 * <b>비공개로 저장해둔 코스가 고치는 것만으로 공개된다.</b>
 *
 * <p>⚠️ 남의 코스를 "나도 짜보기"로 담아 오는 길에는 넣지 않는다. 그쪽은 코스 번호를
 * 애초에 받지 않으므로(홈 응답에서 뺐다) 저절로 새 코스가 된다.
 */
export interface TripSource {
  /** 저장된 코스 번호 */
  courseId: number
  /** 저장해둔 이름 */
  name: string
  /** 저장해둔 공개 여부 */
  isPublic: boolean
}

/**
 * 이 여행이 <b>어디서 시작됐나.</b>
 *
 * <p>결과 화면이 "바꾼 것이 없다"를 두 가지로 갈라 말하기 위해 필요하다(2026-09-10).
 * 설문(FULL PEAKOFF)이 짜 준 코스를 그대로 진단까지 가져간 사람은 <b>새 여행지를 발견한</b>
 * 것이고, 손으로 짠 코스를 바꾸지 않은 사람은 <b>이미 여유로운 여행을 확인한</b> 것이다.
 * 둘 다 "원안 그대로입니다"로 뭉개면 한 일이 없는 것처럼 읽힌다.
 *
 * <p>⚠️ 예전에는 이 표식이 없었다. 설문 초안은 {@code restore(plan, days)}로 넘어와
 * 손으로 짠 코스와 상태상 구분되지 않았다 — 원안(baseline)을 일부러 비워 "시스템이 짠 코스 대비
 * 개선폭"을 재지 않게 한 설계라, 그 뒤에는 출처를 알 길이 없었다. 판단은 여기서만 한다.
 *
 * <ul>
 *   <li>{@code manual} — 조건 입력 → 지도에서 직접 담은 코스. 남의 코스를 베낀 것과
 *       마이페이지에서 다시 연 것도 여기다: 그 코스를 <b>고르고 진단한 사람</b>은 사용자다</li>
 *   <li>{@code survey} — 설문 두 문항으로 서버가 짜 준 초안에서 시작한 코스</li>
 * </ul>
 */
export type TripOrigin = 'manual' | 'survey'

export interface TripState {
  plan: TripPlan | null
  days: string[][]
  baseline: TripBaseline | null
  /** 고쳐 쓰는 중이면 그 코스. 새로 짜는 중이면 null */
  source: TripSource | null
  /** 어디서 시작한 여행인가. 편집 도중에는 바뀌지 않고, 새 여행을 시작할 때만 다시 정해진다 */
  origin: TripOrigin
}
