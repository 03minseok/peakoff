/**
 * 프로필 자리에 놓는 기본 그림.
 *
 * <h3>왜 이니셜을 걷어냈나</h3>
 * 닉네임 첫 글자를 큼직하게 박아 두었는데, 바로 옆에 <b>같은 닉네임이 전체로 다시 적혀</b> 있다.
 * 같은 정보가 두 번 서면서 정작 "프로필 사진 자리"라는 것이 안 읽혔다 — 글자가 들어 있으니
 * 그림이 아니라 배지처럼 보인다.
 *
 * <p>사람 실루엣은 <b>비어 있음을 그대로 말한다.</b> 카카오톡·라인처럼 사진을 올리기 전의
 * 기본 그림이 이 모양인 것도 같은 이유다 — 보는 순간 "아직 사진이 없다"로 읽힌다.
 * 나중에 사진 올리기를 붙이면 이 자리를 그대로 갈아끼우면 된다.
 *
 * <h3>색</h3>
 * 회색 hex를 박지 않는다. 바탕은 {@code --c-fill}("지금은 신호가 아니다"를 말하는 옅은 채움),
 * 실루엣은 {@code --c-hint}를 흐리게 깔아 만든다. <b>일부러 약하게</b> 두었다 —
 * 이 그림은 아무 정보도 나르지 않으므로, 옆에 선 닉네임보다 무거우면 안 된다.
 *
 * <p>⚠️ 브랜드 틸을 쓰지 않는다. 브랜드색은 행동을 청하는 자리와 강조의 것이고,
 * 여기는 <b>비어 있는 자리</b>다. 색을 주면 누를 수 있는 것처럼 읽힌다.
 */
export function ProfileAvatar({ className = '' }: { className?: string }) {
  return (
    <span
      className={`bg-fill text-hint grid flex-none place-items-center overflow-hidden ${className}`}
      aria-hidden="true"
    >
      {/*
        머리(원)와 어깨(아래가 잘린 둥근 덩어리). 어깨를 상자 바닥까지 내려
        <b>테두리에 걸쳐 잘리게</b> 두는 것이 이 그림의 특징이다 — 잘리지 않으면
        사람이 상자 안에 떠 있는 것처럼 보인다.
      */}
      <svg viewBox="0 0 64 64" className="h-full w-full" fill="currentColor" opacity="0.32">
        <circle cx="32" cy="24" r="11.5" />
        <path d="M32 39c-11.6 0-21 9.4-21 21v4h42v-4c0-11.6-9.4-21-21-21z" />
      </svg>
    </span>
  )
}
