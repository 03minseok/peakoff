/**
 * 로고 마크 — 봉우리와, 그 옆으로 비껴간 한 칸.
 *
 * <h3>무엇을 그린 것인가</h3>
 * 이름 그대로다. <b>PEAK</b>는 혼잡의 정점이고, <b>OFF</b>는 거기서 낮추어 비껴가는 일이다.
 * 그래서 봉우리(Λ)의 오른쪽 다리가 땅까지 내려오지 않고 중간에서 끊기고,
 * 끊긴 자리에서 한 칸 옆으로 비껴간 조각이 브랜드색으로 남는다.
 *
 * <pre>
 *      /\
 *     /  \        왼쪽 다리는 바닥까지 — 붐비는 길
 *    /    \       오른쪽은 도중에 한 번 끊기고
 *   /      \      같은 결로 이어 내려온다  ← 브랜드색
 * </pre>
 *
 * <h3>색은 팔레트에서 온다</h3>
 * 로고 원본의 파랑을 그대로 쓰지 않는다. 색의 원천은 {@code index.css}의 {@code --c-*}
 * 한 곳이어야 하고, 서비스가 미는 방향(한적)은 이미 틸이 맡고 있다.
 * 봉우리는 잉크, 비껴간 조각은 브랜드 틸이다.
 *
 * <p>⚠️ {@code currentColor}를 쓰지 않는다. 두 조각의 색이 <b>서로 달라야</b>
 * 마크가 성립하는데, currentColor로 두면 글자색을 물려받아 한 덩어리로 뭉친다.
 *
 * <h3>어두운 면에서는 두 색이 모두 바뀐다</h3>
 * 봉우리는 흰색, 비껴간 조각은 <b>그린틸</b>({@code --c-quiet-soft})이다.
 * 어두운 패널에는 틸 글로우가 깔려 있어 브랜드 틸을 그대로 두면 배경에 묻히고,
 * 같은 면의 틸 버튼과 무게가 겹쳐 <b>로고가 행동 유도로 읽힌다.</b>
 */

interface Props {
  /** 배경. 어두운 면에서는 두 색이 함께 바뀐다 */
  tone?: 'light' | 'dark'
  /** 상자 한 변(px). 도형은 그 안에서 여백을 두고 그려진다 */
  size?: number
  className?: string
}

/*
 * ■ 좌표를 어떻게 잡았는가 (viewBox 0 0 32 32)
 *
 * 두 다리의 기울기를 <b>세로 2 : 가로 1</b>로 고정하고, 획의 두께(수직 기준 5)에서
 * 안쪽 꼭짓점을 계산해 넣었다. 눈대중으로 안쪽 선을 그으면 획이 위로 갈수록 얇아져,
 * 작은 크기에서 봉우리 끝이 먼저 사라진다.
 *
 *   바깥 꼭짓점 (16, 6)에서 안쪽 꼭짓점은 아래로 w√5 = 11.18 → (16, 17.18)
 *
 * 소수점이 붙은 값(17.41 · 17.18 · 11.59)이 그 계산 결과다. 반올림하면 획 두께가
 * 자리마다 달라진다.
 *
 * ■ 조각은 <b>다리를 그대로 이어</b> 내려온다
 * 조각의 좌우 변은 다리와 <b>같은 직선 위</b>에 있다. 기울기만 같은 것이 아니라
 * 연장선이 정확히 겹친다 — 바깥 변은 꼭짓점 (16,6)에서, 안쪽 변은 (16,17.18)에서
 * 뻗어 나온 같은 선이다. 그래서 아래 두 좌표는 손으로 정한 값이 아니라
 * <b>그 두 직선 위에서 y만 정하면 따라 나오는 값</b>이다.
 *
 * <p>⚠️ 한때 조각을 옆으로 꺾어 두었다. "비껴간다"를 각도로 표현하려 한 것인데,
 * 획이 도중에 <b>휘어 보였다.</b> 비껴감은 각도가 아니라 <b>끊김</b>이 맡는다.
 *
 * ■ 사이를 띄운다
 * 다리는 y=20에서 끊기고 조각은 y=21.4에서 시작한다. 획을 따라 잰 틈은 1.57로,
 * 획 폭(5.0)의 31%다. 맞붙여 두면 색만 갈린 한 덩어리라 <b>끊겼다는 것이 안 보이고</b>,
 * 더 벌리면 두 개의 다른 도형이 된다. 그 사이 폭이다.
 *
 * ■ 도형은 상자 한가운데 온다
 * 조각이 바닥까지 내려오면서 좌우 폭이 꼭짓점을 기준으로 대칭이 됐다(±10).
 * 그래서 꼭짓점을 상자 한가운데(x=16)에 두는 것만으로 정렬이 끝난다 —
 * 칠해지는 범위가 x 6~26 · y 6~26이라 사방 여백이 모두 6.0이다.
 * 예전처럼 어긋난 폭을 상쇄하려고 전체를 옮겨 둘 필요가 없어졌다.
 */

/** 봉우리. 왼쪽 다리는 바닥(y=26)까지, 오른쪽은 y=20에서 끊긴다. */
const PEAK_PATH = 'M16 6 L23 20 L17.41 20 L16 17.18 L11.59 26 L6 26 Z'

/**
 * 끊긴 자리에서 이어지는 조각. 다리의 두 변을 그대로 연장한 자리에 놓이고,
 * 사이를 조금 띄운 채 바닥(y=26)에 닿는다.
 *
 * <h3>⚠️ 값을 네 번 고쳤다 (2026-08-27)</h3>
 * 무엇을 놓쳤는지 순서대로 남겨 둔다. 같은 자리를 또 건드릴 때 되풀이하지 않으려는 것이다:
 * <ul>
 *   <li>{@code M20 20 L26.8 20 L28.8 24 L22 24 Z} — 바닥이 y=24라 봉우리(y=26)보다
 *       떠 있었고, 가로 두께 6.8이 다리(5.59)보다 두꺼웠다</li>
 *   <li>{@code … L28.59 26 L23 26 Z} — 바닥과 두께는 맞췄지만 <b>모서리 한 점</b>으로만
 *       만났다. 접점의 넓이가 0이라 화면에서는 여전히 떨어져 보였다</li>
 *   <li>{@code M16.11 20 L21.7 20 …} — 잘린 면 전체를 맞대 붙이긴 했으나
 *       조각이 다리와 다른 각도로 뻗어 <b>획이 휘어 보였다</b></li>
 *   <li>지금 값 — <b>각도를 다리와 일치</b>시키고, 붙이는 대신 <b>틈을 두었다</b></li>
 * </ul>
 *
 * <p>네 점 모두 계산값이다. 바깥 변은 {@code x = 16 + (y − 6)/2}, 안쪽 변은
 * {@code x = 16 + (y − 17.18)/2} 위에 있고, 거기에 y = 21.4와 y = 26을 넣으면 나온다.
 * 눈대중으로 옮기면 연장선이 어긋나 다시 휘어 보인다.
 */
const OFFSET_PATH = 'M18.11 21.4 L23.7 21.4 L26 26 L20.41 26 Z'

export function BrandMark({ tone = 'light', size = 26, className = '' }: Props) {
  const peak = tone === 'dark' ? '#FFFFFF' : 'var(--c-fg)'
  const offset = tone === 'dark' ? 'var(--c-quiet-soft)' : 'var(--c-brand)'

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 32 32"
      fill="none"
      className={`flex-none ${className}`}
      aria-hidden="true"
    >
      <path d={PEAK_PATH} fill={peak} />
      <path d={OFFSET_PATH} fill={offset} />
    </svg>
  )
}

/**
 * 마크와 글자를 함께 세운 로고.
 *
 * <p>네 화면(헤더 둘·로그인·가입 패널)이 같은 것을 각자 그리고 있었다. 한 곳으로 모으면
 * 마크를 고칠 때 <b>한 자리만 고치면 된다</b> — 예전에는 네 곳 중 하나를 빠뜨리면
 * 화면마다 다른 로고가 서 있었다.
 *
 * <p>글자는 <b>PEAKOFF</b>로 붙여 쓴다. 서비스 이름이 한 낱말이라 그렇다 —
 * 두 낱말(PEAK / OFF)의 뜻은 마크가 이미 그림으로 말하고 있고,
 * 자간(tracking)이 벌어져 있어 붙여 써도 두 덩어리로 읽힌다.
 *
 * <p>마크에 사방 여백이 들어 있어 {@code gap}은 좁게 둔다 — 넉넉히 주면
 * 마크의 여백과 더해져 글자가 멀리 떨어져 보인다.
 */
export function BrandLockup({ tone = 'light', size = 26, className = '' }: Props) {
  return (
    <span className={`flex items-center gap-1 ${className}`}>
      <BrandMark tone={tone} size={size} />
      <span
        className={`text-xs font-bold tracking-[0.16em] ${
          tone === 'dark' ? 'text-white' : 'text-fg'
        }`}
      >
        PEAKOFF
      </span>
    </span>
  )
}
