/**
 * 로고 마크 — 봉우리와, 그 옆으로 비껴간 한 칸.
 *
 * <h3>무엇을 그린 것인가</h3>
 * 이름 그대로다. <b>PEAK</b>는 혼잡의 정점이고, <b>OFF</b>는 거기서 낮추어 비껴가는 일이다.
 * 그래서 봉우리(Λ)의 오른쪽 다리가 땅까지 내려오지 않고 중간에서 끊기고,
 * 끊긴 자리에서 한 칸 옆으로 비껴간 조각이 브랜드색으로 남는다.
 *
 * <pre>
 *      /\
 *     /  \        왼쪽 다리는 바닥까지 — 붐비는 길
 *    /    \_      오른쪽은 도중에 꺾여
 *   /       \     한 칸 옆으로 비껴 내려온다  ← 브랜드색
 * </pre>
 *
 * <h3>색은 팔레트에서 온다</h3>
 * 로고 원본의 파랑을 그대로 쓰지 않는다. 색의 원천은 {@code index.css}의 {@code --c-*}
 * 한 곳이어야 하고, 서비스가 미는 방향(한적)은 이미 틸이 맡고 있다.
 * 봉우리는 잉크, 비껴간 조각은 브랜드 틸이다.
 *
 * <p>⚠️ {@code currentColor}를 쓰지 않는다. 두 조각의 색이 <b>서로 달라야</b>
 * 마크가 성립하는데, currentColor로 두면 글자색을 물려받아 한 덩어리로 뭉친다.
 *
 * <h3>어두운 면에서는 두 색이 모두 바뀐다</h3>
 * 봉우리는 흰색, 비껴간 조각은 <b>그린틸</b>({@code --c-quiet-soft})이다.
 * 어두운 패널에는 틸 글로우가 깔려 있어 브랜드 틸을 그대로 두면 배경에 묻히고,
 * 같은 면의 틸 버튼과 무게가 겹쳐 <b>로고가 행동 유도로 읽힌다.</b>
 */

interface Props {
  /** 배경. 어두운 면에서는 두 색이 함께 바뀐다 */
  tone?: 'light' | 'dark'
  /** 상자 한 변(px). 도형은 그 안에서 여백을 두고 그려진다 */
  size?: number
  className?: string
}

/*
 * ■ 좌표를 어떻게 잡았는가 (viewBox 0 0 32 32)
 *
 * 두 다리의 기울기를 <b>세로 2 : 가로 1</b>로 고정하고, 획의 두께(수직 기준 5)에서
 * 안쪽 꼭짓점을 계산해 넣었다. 눈대중으로 안쪽 선을 그으면 획이 위로 갈수록 얇아져,
 * 작은 크기에서 봉우리 끝이 먼저 사라진다.
 *
 *   바깥 꼭짓점 (14.7, 6)에서 안쪽 꼭짓점은 아래로 w√5 = 11.18 → (14.7, 17.18)
 *
 * 소수점이 붙은 값(16.11 · 17.18 · 10.29)이 그 계산 결과다. 반올림하면 획 두께가
 * 자리마다 달라진다.
 *
 * ■ 두 조각은 잘린 면 전체를 맞댄다
 * ⚠️ 예전에는 <b>모서리 한 점</b>으로만 만났다. 계산상으로는 붙어 있지만 눈에는
 * 떨어진 두 도형이었다 — 접점의 넓이가 0이라 어느 크기에서도 이어져 보이지 않는다.
 * 오른쪽 다리가 끊긴 면 (14.41,20)~(20,20) <b>전체</b>를 조각의 윗변으로 쓴다.
 * 그러면 한 붓으로 그린 획이 도중에 옆으로 꺾인 모양이 된다.
 *
 * ■ 꺾이는 폭은 제 두께만큼
 * 조각의 밑변은 윗변에서 오른쪽으로 <b>획 두께(5.59)만큼</b> 옮겨 간다. 그래서
 * 왼쪽 아래 모서리 (20,26)이 끊긴 면의 오른쪽 끝 바로 아래에 온다 —
 * "한 칸 옆으로"라는 말이 눈금 그대로 지켜진다.
 *
 * ■ 도형은 상자 한가운데 온다
 * 위 변경으로 칠해지는 범위가 x 3~25.59로 좁아져 오른쪽 여백이 6.41까지 벌어졌다.
 * 그래서 <b>모든 좌표를 오른쪽으로 1.7 옮겼다</b>. 지금은 x 4.7~27.29 · y 6~26이라
 * 사방 여백이 4.7 / 4.71 / 6.0 / 6.0이다. 글자 옆에 세웠을 때 마크만 한쪽으로
 * 쏠리지 않게 하려는 것이다. 소수점이 붙은 값들이 그래서 더 지저분해졌다.
 */

/** 봉우리. 왼쪽 다리는 바닥(y=26)까지, 오른쪽은 y=20에서 끊긴다. */
const PEAK_PATH = 'M14.7 6 L21.7 20 L16.11 20 L14.7 17.18 L10.29 26 L4.7 26 Z'

/**
 * 비껴간 조각. 윗변이 <b>끊긴 다리의 잘린 면 그 자체</b>이고, 거기서 오른쪽으로
 * 획 두께만큼 밀려 바닥(y=26)에 닿는다. 위·아래 변은 수평, 좌우 변은 서로 평행이다.
 *
 * <h3>⚠️ 점이 아니라 면으로 잇는다 (2026-08-27)</h3>
 * 값을 두 번 고쳤고, 앞의 두 값이 무엇을 놓쳤는지 남겨 둔다:
 * <ul>
 *   <li>{@code M20 20 L26.8 20 L28.8 24 L22 24 Z} — 바닥이 y=24라 봉우리(y=26)보다
 *       2만큼 떠 있었고, 가로 두께 6.8이 다리(5.59)보다 두꺼웠다</li>
 *   <li>{@code M20 20 L25.59 20 L28.59 26 L23 26 Z} — 바닥과 두께는 맞췄지만
 *       <b>모서리 한 점 (20,20)으로만</b> 봉우리와 만났다. 접점의 넓이가 0이라
 *       화면에서는 여전히 <b>떨어진 두 도형</b>으로 보였다. 이것이 실제 문제였다</li>
 * </ul>
 *
 * <p>지금은 잘린 면 (16.11,20)~(21.7,20)을 <b>윗변으로 통째로</b> 쓴다. 이으려면
 * 맞닿는 것이 점이 아니라 <b>선분</b>이어야 한다 — 두 도형이 한 획으로 읽히는 조건이다.
 * 밑변은 그 면의 오른쪽 끝(21.7) 아래에서 시작해 두께 5.59만큼 뻗는다.
 */
const OFFSET_PATH = 'M16.11 20 L21.7 20 L27.29 26 L21.7 26 Z'

export function BrandMark({ tone = 'light', size = 26, className = '' }: Props) {
  const peak = tone === 'dark' ? '#FFFFFF' : 'var(--c-fg)'
  const offset = tone === 'dark' ? 'var(--c-quiet-soft)' : 'var(--c-brand)'

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 32 32"
      fill="none"
      className={`flex-none ${className}`}
      aria-hidden="true"
    >
      <path d={PEAK_PATH} fill={peak} />
      <path d={OFFSET_PATH} fill={offset} />
    </svg>
  )
}

/**
 * 마크와 글자를 함께 세운 로고.
 *
 * <p>네 화면(헤더 둘·로그인·가입 패널)이 같은 것을 각자 그리고 있었다. 한 곳으로 모으면
 * 마크를 고칠 때 <b>한 자리만 고치면 된다</b> — 예전에는 네 곳 중 하나를 빠뜨리면
 * 화면마다 다른 로고가 서 있었다.
 *
 * <p>글자는 <b>PEAK OFF</b>로 띄운다. 로고가 그렇게 쓰고, 마크가 그 두 낱말을
 * 그림으로 옮긴 것이라 붙여 쓰면 그림과 글자가 다른 말을 하게 된다.
 *
 * <p>마크에 사방 여백이 들어 있어 {@code gap}은 좁게 둔다 — 넉넉히 주면
 * 마크의 여백과 더해져 글자가 멀리 떨어져 보인다.
 */
export function BrandLockup({ tone = 'light', size = 26, className = '' }: Props) {
  return (
    <span className={`flex items-center gap-1 ${className}`}>
      <BrandMark tone={tone} size={size} />
      <span
        className={`text-xs font-bold tracking-[0.16em] ${
          tone === 'dark' ? 'text-white' : 'text-fg'
        }`}
      >
        PEAK OFF
      </span>
    </span>
  )
}
