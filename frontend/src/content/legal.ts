/** 문서를 가리키는 값. 동의 항목과 시트가 이 값으로 이어진다. */
export type LegalDocId = 'tos' | 'privacy'

/**
 * 작은 제목을 단 목록.
 *
 * <p>"수집하는 항목"처럼 <b>한 조항 안에서 경우가 갈리는</b> 자리에 쓴다.
 * 이게 없으면 조항을 억지로 쪼개게 되고, 번호가 붙은 조항 사이에 번호 없는 조항이 끼어든다.
 */
interface LegalGroup {
  label: string
  items: string[]
}

interface LegalSection {
  heading: string
  /** 조항 첫머리 문단. `\n`으로 줄을 나눌 수 있다 */
  body?: string[]
  /** 글머리 목록 */
  items?: string[]
  /** 경우가 갈리는 목록 */
  groups?: LegalGroup[]
  /** 목록 아래에 붙는 마무리 문장 */
  footnote?: string
}

export interface LegalDocument {
  title: string
  /** 시행일. 문서를 고치면 반드시 함께 올린다 */
  effectiveDate: string
  intro?: string
  sections: LegalSection[]
}

