package com.peakoff.congestion.domain;

/**
 * 한적도를 3단계로 묶은 등급. 화면의 배지 표시에 쓴다.
 *
 * <p>숫자 대신 등급을 함께 내려보내는 이유: 임계값이 서버 한 곳에만 있어야
 * 나중에 분석 결과로 기준이 바뀔 때 프론트를 건드리지 않는다.
 *
 * <h3>경계를 65 / 35로 정한 근거 (2026-08-31 실측)</h3>
 *
 * <p>전국 16개 시도에서 시군구를 고르게 뽑아 <b>64개 시군구 · 관광지 2,905곳 ·
 * 관측 87,150건</b>의 집중률 예측을 받아 분포를 쟀다. 그전까지 쓰던 70 / 40은
 * 서비스 지역(경주·제주시·서귀포) 셋만 보고 화면에서 구분되는 수준으로 잡은 값이었다.
 *
 * <p><b>전국을 보고 나서야 드러난 것은 우리 지역이 전국에서 붐비는 축이라는 사실이다.</b>
 * 시도별 한적도 중앙값이 서울 37.4 · 제주 46.7부터 경남 68.6 · 강원 67.6까지
 * <b>32점</b> 벌어져 있고, 경북(65.5)과 제주가 그 중 아래쪽에 있다. 서비스 지역만 보고
 * 잡은 경계는 그래서 전국에서 그대로 통하지 않는다.
 *
 * <p><b>하나의 절대 경계로 전국과 서비스 지역을 동시에 고르게 가를 수는 없다.</b>
 * 격자 탐색으로 확인했다 — "가장 불리한 시도에서 가장 적게 쓰이는 배지의 비율"을
 * 최대화해도 최적이 16.7%(경계 62 / 39)이고, 그 대가로 전국의 46.5%가 "한적"이 되어
 * 배지가 기본값으로 읽힌다. 시도별 중앙값이 32점 벌어져 있는 한 구조적인 상충이다.
 *
 * <p>그래서 이 값은 실측 분위수가 아니라 <b>두 조건을 함께 만족하는 절충</b>이다.
 * 분위수로 잡는 방법(추천도 구간 경계가 쓴 방법)은 3개 지역만 볼 때만 성립했다.
 *
 * <pre>
 *                 전국(한적/보통/붐빔)   서비스 3지역        제주시 한적   최악 시도의 최소 배지
 *   70 / 40  전   31.4 / 40.6 / 28.0   15.6 / 46.4 / 38.0     11.3%          7.7%
 *   65 / 35  후   41.3 / 35.1 / 23.6   22.8 / 45.8 / 31.3     18.2%         12.6%
 * </pre>
 *
 * <p>고른 이유는 셋이다.
 * <ul>
 *   <li><b>양쪽 다 산다.</b> 전국에서도 서비스 지역에서도 세 배지가 모두 쓰인다.
 *       어느 한쪽이 45%를 넘지 않는다 — 넘으면 그 배지가 기본값이 되어 신호를 잃는다.</li>
 *   <li><b>확장 방향이 안전하다.</b> 지역을 늘리면 들어올 곳은 대개 지금보다 조용한 지역이다.
 *       65 / 35는 그쪽에서 한적이 늘 뿐 배지가 죽지 않는다. 서비스 3개 지역의 분위수로
 *       잡았을 값(63 / 30)은 그때 전국 한적이 44.9%가 되어 무너진다.</li>
 *   <li><b>가장 불리한 지역이 나아진다.</b> 서울 기준 최소 배지가 7.7% → 12.6%,
 *       30일 내내 배지가 한 종류인 관광지가 서귀포에서 16.7% → 13.7%로 줄었다.</li>
 * </ul>
 *
 * <p>⚠️ 경계를 옮기면 {@link com.peakoff.course.domain.survey.CrowdSensitivity}의
 * "붐비는 곳 제외"가 걸러내는 범위도 함께 움직인다. 붐빔 하한이 내려가면 후보가 넓어지므로
 * <b>"고른 답이 후보를 거른다"는 함정에서 멀어지는 방향</b>이다.
 *
 * <p>측정 스크립트는 {@code analysis/national/}에 있다. 검증용이며 서비스는 읽지 않는다.
 */
public enum CongestionLevel {

	/** 붐빌 것으로 예상. */
	CROWDED("붐빔", "예상 혼잡 다소 높음"),

	MODERATE("보통", "예상 혼잡 보통"),

	/** 한적할 것으로 예상. */
	QUIET("한적", "예상 혼잡 낮음");

	/**
	 * 이 위로 "한적". 전국 표본의 41.3% · 서비스 3개 지역의 22.8%가 여기 든다.
	 *
	 * <p>더 올리면(70 이상) 제주에서 한적 배지가 열에 하나로 줄어 신호 노릇을 못 하고,
	 * 더 내리면(63 이하) 전국의 절반 가까이가 한적이 되어 배지가 기본값이 된다.
	 */
	public static final int QUIET_THRESHOLD = 65;

	/**
	 * 이 아래가 "붐빔". 전국 표본의 23.6% · 서비스 3개 지역의 31.3%가 여기 든다.
	 *
	 * <p>전국 3등분 경계(46)까지 올리면 제주가 절반 붐빔이 되어, 어느 날이 나은지를
	 * 배지로 알 수 없게 된다.
	 */
	public static final int MODERATE_THRESHOLD = 35;

	private final String label;
	private final String congestionPhrase;

	CongestionLevel(String label, String congestionPhrase) {
		this.label = label;
		this.congestionPhrase = congestionPhrase;
	}

	public static CongestionLevel fromQuietness(int quietness) {
		if (quietness >= QUIET_THRESHOLD) {
			return QUIET;
		}
		if (quietness >= MODERATE_THRESHOLD) {
			return MODERATE;
		}
		return CROWDED;
	}

	/** 배지에 쓰는 짧은 말: 한적 / 보통 / 붐빔 */
	public String label() {
		return label;
	}

	/**
	 * 추천 근거 문구에 쓰는 표현: "예상 혼잡 낮음" 등.
	 *
	 * <p>예측·통계값이므로 "실시간"이라는 표현을 쓰지 않는다.
	 */
	public String congestionPhrase() {
		return congestionPhrase;
	}
}
