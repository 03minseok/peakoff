package com.peakoff.congestion.domain;

/**
 * 한적도를 매기지 못한 이유.
 *
 * <h3>왜 "자료 없음" 하나로 두지 않는가</h3>
 * 두 가지는 사용자에게 <b>완전히 다른 소식</b>이다.
 * 하나는 기다리면 생기고, 하나는 기다려도 생기지 않는다.
 * 같은 회색 칸으로 뭉개면 사용자는 "이 서비스는 데이터가 부실하다"고 읽는다.
 *
 * <h3>왜 0점으로 채우지 않는가</h3>
 * 0점은 화면에서 <b>"매우 붐빔"</b>으로 읽힌다. 자료가 없다는 사실이 "최악의 장소"라는
 * 거짓말로 바뀌고, 코스 총점까지 끌어내린다. 계산하지 않은 것을 근거로 말하지 않는다는
 * 규칙이 정확히 이 자리를 막는다.
 */
public enum DiagnosisGap {

	/**
	 * <b>관광지인데</b> 예측 목록에 없다. 날짜를 바꿔도 없다.
	 *
	 * <p>공사는 관광지 중에서도 일부만 예측한다 — 경주 역사·유적 109곳 중 36곳뿐이다.
	 * 그래서 같은 왕릉인데 어떤 곳은 점수가 뜨고 어떤 곳은 안 뜬다.
	 *
	 * <p><b>이 자리에서는 말을 해야 한다.</b> 침묵하면 사용자는 담는 방법을 잘못 알았다고
	 * 생각하고 자기 탓을 찾는다. "우리가 못 매긴 것"이라고 밝히는 편이 정확하다.
	 */
	PLACE_NOT_FORECASTED("예상 혼잡 정보가 없는 장소예요"),

	/**
	 * 애초에 예측 대상 분류가 아니다. 음식점·숙박·쇼핑이 여기다.
	 *
	 * <p><b>문구가 없다.</b> 경주 621곳 중 음식점이 211곳, 숙박이 121곳이다. 코스에
	 * 밥집이 서넛만 있어도 안내가 화면을 채워 정작 읽어야 할 점수들이 그 사이에 묻힌다.
	 * 예측하지 않기로 되어 있는 것을 "없다"고 알리는 것은 정보가 아니다.
	 *
	 * <p>{@link #PLACE_NOT_FORECASTED}와 값을 갈라 둔 이유가 이것이다. 사실은 같지만
	 * (자료가 없다) <b>사용자에게 할 말이 다르다.</b> 어느 쪽인지는 분류로 가른다
	 * ({@code PlaceCategories.isForecastTarget}).
	 */
	CATEGORY_NOT_FORECASTED(null),

	/**
	 * 장소는 예측 대상인데 그 날짜가 예측 범위 밖이다.
	 *
	 * <p>예측은 조회 시점부터 3~4주치만 나온다. <b>여행일이 다가오면 생긴다</b> —
	 * 그래서 "나중에 다시 진단해 보세요"라고 말할 수 있는 자리다.
	 */
	DATE_OUT_OF_FORECAST("아직 예측이 나오지 않은 날짜예요");

	private final String message;

	DiagnosisGap(String message) {
		this.message = message;
	}

	/**
	 * 화면에 그대로 띄울 수 있는 문구. <b>할 말이 없으면 {@code null}이다.</b>
	 *
	 * <p>서버가 문구를 들고 있는 이유는 임계값·가중치를 서버에 두는 것과 같다 —
	 * 판단의 근거와 그 판단을 설명하는 말이 갈라지면 한쪽만 바뀐다.
	 *
	 * <p>비어 있을 수 있게 둔 것도 같은 이유다. "이 자리에 말을 걸지 말지"는 판단이지
	 * 화면의 취향이 아니다. 화면이 {@code null}을 보고 조용히 넘기면, 나중에 공사가
	 * 음식점을 예측하기 시작해도 화면은 그대로 두고 여기만 고치면 된다.
	 */
	public String message() {
		return message;
	}
}
