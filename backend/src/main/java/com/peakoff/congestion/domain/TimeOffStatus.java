package com.peakoff.congestion.domain;

/**
 * 날짜를 옮기라고 권할지에 대한 판단.
 *
 * <h3>왜 참·거짓 하나로 두지 않는가</h3>
 * 예전에는 {@code alreadyQuietest} 하나였다. 그러면 화면이 할 수 있는 말이 두 가지뿐인데,
 * 실제로 사용자가 알아야 할 사정은 다섯 가지다. "더 나은 날이 없다"와 "자료를 못 불러왔다"와
 * "이미 충분히 한적하다"는 <b>전혀 다른 소식</b>인데 한 값으로는 구분되지 않는다.
 *
 * <h3>순서가 규칙이다</h3>
 * 위에서부터 먼저 들어맞는 것을 쓴다. 자료가 없으면 한적한지 따질 수 없고, 이미 한적하면
 * 더 나은 날이 있어도 굳이 옮기라고 하지 않는다. 조건을 병렬로 두면 두 개가 동시에 참이 될 때
 * 어느 쪽을 보여줄지가 코드 순서에 따라 우연히 정해진다.
 *
 * <h3>왜 "이미 한적하면" 권하지 않는가</h3>
 * 코스 전체가 한적한데도 1점 더 나은 날을 들이밀면, 서비스가 <b>쓸데없이 참견하는 것</b>이 된다.
 * 여행 날짜를 옮기는 것은 숙소·교통까지 딸린 큰 결정이라, 그만한 이유가 있을 때만 권해야 한다.
 */
public enum TimeOffStatus {

	/**
	 * 계산할 자료가 없다. 기준일을 계산할 수 없거나 비교할 후보가 하나도 유효하지 않다.
	 *
	 * <p>공사 예측은 조회 시점부터 3~4주치뿐이다. 그보다 먼 여행은 여기에 걸린다.
	 */
	INSUFFICIENT_DATA("날짜 정보를 충분히 불러오지 못했어요"),

	/** 지금 일정이 이미 한적하다. 옮길 이유가 없다. */
	ALREADY_QUIET("지금 일정도 충분히 여유로워요"),

	/** 앞뒤를 다 봐도 지금 날짜보다 나은 날이 없다. */
	CURRENT_BEST("선택한 날짜가 앞뒤 며칠 중 가장 한적해요"),

	/** 더 나은 날이 있지만 차이가 크지 않다. 옮길 만한 값어치가 없다. */
	MARGINAL("날짜별 혼잡 차이가 크지 않아요"),

	/** 옮길 만하다. 화면이 개선폭을 강조해도 되는 유일한 상태다. */
	RECOMMENDED("더 한적한 날짜가 있어요");

	private final String message;

	TimeOffStatus(String message) {
		this.message = message;
	}

	public String message() {
		return message;
	}

	/** 날짜를 옮기라고 <b>적극적으로</b> 권하는 상태인지. 화면의 강조 여부가 여기 걸린다. */
	public boolean recommendsChange() {
		return this == RECOMMENDED;
	}
}
