package com.peakoff.chat.domain;

import java.util.Map;
import java.util.Objects;

import com.peakoff.place.domain.SupportedRegion;

/**
 * 지역 하나를 챗봇이 견주는 데 필요한 것만 담은 요약.
 *
 * <h2>숫자가 둘이고, 하는 일이 다르다</h2>
 * <ul>
 *   <li>{@code shares} — 관심사별 <b>몫</b>. 후보를 <b>거르는</b> 데만 쓴다</li>
 *   <li>{@code quietShare} — 창 안의 <b>한적한 예측의 비율</b>. <b>줄 세우는</b> 데 쓰고,
 *       그대로 <b>카드에 적힌다</b></li>
 * </ul>
 * 둘을 곱하거나 더해 하나로 만들지 않는다. 합치는 순간 "왜 이 지역이 1등인지"를
 * 화면이 설명하지 못한다.
 *
 * <h2>⚠️ 왜 "지역 평균 한적도"가 아닌가 (2026-09-05 실측)</h2>
 * 설계는 원래 <b>지역 평균 한적도</b>로 줄을 세우고 그 값에 3단계 배지를 걸려 했다.
 * 11개 지역을 실제로 재 보니 <b>전부 보통이었다</b>:
 *
 * <pre>
 * 제주시 48 · 서귀포 49 · 경주 57 · 속초 58 · 춘천 59 · 여수 60 · 태안 60
 * 충주 61 · 남원 61 · 가평 62 · 통영 63          ← 한적(65) 위도, 붐빔(35) 아래도 없다
 * </pre>
 *
 * 카드 둘의 배지가 언제나 같은 글자가 되어, "여러 개를 나란히 놓아 차이를 보인다"는
 * 이 화면의 존재 이유가 사라진다. {@code docs/OPEN_DECISIONS.md} 11-1이 적어 둔 함정과
 * 같은 뿌리다 — <b>표본을 늘릴수록 평균은 좁아진다.</b> 지역 하나가 50~244곳 × 7일이라
 * 가장 붐비는 곳과 가장 한적한 곳이 서로를 지운다.
 *
 * <p>같은 원자료에서 폭이 살아 있는 통계를 찾아 넷을 나란히 쟀다:
 *
 * <pre>
 *                              폭        비고
 * 관측 전체 평균        48 ~ 63   15    11곳 전부 "보통"
 * 최고 한적일 평균      59 ~ 78   19    9곳이 "한적" — 가장 좋은 날만 골라 뻥튀기
 * 한적 관측 비율        22 ~ 65   43    ← 이걸 쓴다
 * 한적 장소 비율        39 ~ 96   57    위쪽에 몰린다(7곳이 78% 이상)
 * </pre>
 *
 * <b>한적 관측 비율</b>은 제주시 21.6%에서 통영 64.7%까지 벌어져, 카드 둘을 나란히 놓으면
 * 차이가 그대로 보인다. "가장 유명한 곳은 붐비고 비슷한 곳은 여유롭다"는 이 서비스의 말이
 * 22% 대 65%라는 숫자로 선다.
 *
 * <h2>⚠️ 셋째 점수가 아니다</h2>
 * 새 척도를 만든 것이 아니라 <b>이미 있는 배지를 세는 것</b>이다. 한적도도 경계(65)도
 * 그대로 쓰고, 지역마다 그 경계를 넘는 예측이 몇 할인지만 본다. 코스 총점의 근거가 얇을 때
 * 평균 대신 <b>등급 요약</b>("한적 2곳 · 보통 1곳")을 펴는 것과 같은 문법이다 —
 * 평균이 감당 못 하는 자리에서 사실을 세어 보인다.
 *
 * <p>무엇보다 이 값은 <b>화면에 그대로 적힌다.</b> 줄 세우는 값이 카드에 보이므로
 * "왜 이게 위에 있는지"를 화면이 스스로 설명한다.
 *
 * @param region       어느 지역
 * @param shares       관심사 → 그 분류가 지역 카탈로그에서 차지하는 몫 (0~1)
 * @param quietShare   창 안의 예측 중 한적(65+)인 관측의 비율 (0~100). 자료가 없으면 {@code null}
 * @param forecastSize 창 안에 예측이 있는 관광지 수. 카드가 모수를 함께 적는 데 쓴다 —
 *                     비율만 내걸면 몇 곳을 보고 한 말인지 알 수 없다
 */
public record RegionProfile(
		SupportedRegion region,
		Map<Interest, Double> shares,
		Integer quietShare,
		int forecastSize) {

	public RegionProfile {
		Objects.requireNonNull(region, "지역은 필수입니다.");
		shares = Map.copyOf(shares);
	}

	/**
	 * 그 관심사가 이 지역에서 차지하는 몫.
	 *
	 * <p>{@link Interest#NONE}이나 자료가 없는 분류는 0이다 — 거르는 쪽에서
	 * "몫이 없으니 통과 못 한다"로 자연스럽게 읽힌다.
	 */
	public double shareOf(Interest interest) {
		return shares.getOrDefault(interest, 0.0);
	}

	/**
	 * 줄 세울 수 있는 지역인가.
	 *
	 * <p>예측 자료가 없으면 이번 주 한적한 정도를 말할 수 없다. 그런 지역은
	 * <b>후보에서 뺀다</b> — 카드에 적을 숫자가 없는 채로 추천하면
	 * "왜 여기를 권하는지"를 화면이 설명하지 못한다.
	 */
	public boolean isRankable() {
		return quietShare != null;
	}
}
