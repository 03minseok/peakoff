package com.peakoff.chat.domain;

/**
 * 카드 한 줄을 <b>서버가</b> 만든다. LLM이 없어도 카드는 완성된다.
 *
 * <h2>왜 서버가 먼저 만드는가</h2>
 * 이 문장은 <b>LLM이 있을 때 더 좋아지는 것</b>이지 LLM이 있어야 생기는 것이 아니다.
 * 인증키가 없거나 · 하루 상한에 닿았거나 · 시간이 초과됐거나 · 답이 검증에 걸렸을 때,
 * 카드에 빈 줄이 서면 <b>화면이 고장으로 읽힌다.</b>
 *
 * <p>순서를 뒤집어 두는 것이 핵심이다 — 템플릿을 먼저 만들고 LLM 문장을 <b>덮어쓴다.</b>
 * "LLM을 부르고 실패하면 템플릿"으로 짜면 실패 경로가 하나 빠질 때마다 빈 카드가 난다.
 *
 * <h2>⚠️ 계산한 것만 말한다</h2>
 * 여기 쓰인 말은 전부 우리가 센 값에서 나온다 — 분류별 몫과 창 안의 한적 관측 비율.
 * "회가 유명해요" 같은 문장은 <b>우리가 계산하지 않은 것</b>이라 여기에도 LLM에게도 없다.
 *
 * <h2>■ 두 장을 견주지 않는다 (2026-09-08)</h2>
 * 오래도록 <b>순위</b>로 말했다 — "이 중에서는 가장 한적한 편이에요" / "…붐비는 편이에요".
 * 지역 평균이 열한 곳 모두 "보통"이라 절대 등급을 걸 수 없었고, 그래서 견주는 말로만
 * 사실을 지킬 수 있었기 때문이다({@link RegionProfile} 참고).
 *
 * <p>그 전제가 사라졌다. 뽑기가 <b>위쪽 절반에서만</b> 두 장을 고르게 되면서
 * ({@link RegionChatPicker}), 두 장 다 "한적한 쪽"이라는 것이 <b>구조로 보장</b>된다.
 * 그러면 굳이 둘을 견줄 이유가 없다 — 견주는 순간 한 장은 <b>덜 좋은 쪽</b>이 되어,
 * 두 장을 준 뜻이 사라진다. 고르는 사람에게 고를 것이 하나뿐이던 것이 그 문제였다.
 *
 * <p>그래서 <b>두 장에 같은 말을 한다.</b> 차이는 카드의 숫자와 막대가 계속 말하고,
 * 문장은 "왜 이 지역이 올라왔는가"만 맡는다.
 *
 * <h2>⚠️ 그래도 단정하지는 않는다</h2>
 * "한적해요"가 아니라 <b>"한적한 곳이 많은 편이에요"</b>다. 우리가 센 것은 지역이 한적하다는
 * 사실이 아니라 <b>그 기간에 한적한 관측이 몇 할인가</b>이고, 카드에 적히는 숫자도 그 값이다.
 * 문장과 숫자가 같은 것을 말하게 두면, 숫자가 무엇인지 문장이 대신 설명해 준다.
 */
public final class CardLineTemplate {

	private CardLineTemplate() {
	}

	/**
	 * @param interest    질문에서 읽은 관심사. 없으면 한적함만 말한다
	 * @param manyQuiet   그 지역에 한적한 곳이 <b>많다고 말해도 되는가</b>
	 *                    ({@link RegionProfile#hasManyQuietSpots})
	 * @return 카드에 적을 한 줄
	 */
	public static String of(Interest interest, boolean manyQuiet) {
		/*
		 * ⚠️ <b>양이 아니라 자리를 말한다</b> (2026-09-08).
		 *
		 * "한적한 곳이 많은 편"은 <b>양</b>을 주장하는 말이다. 주말처럼 붐비는 기간에는
		 * 그 값이 18%까지 떨어지는데, 그때도 같은 말을 하면 화면이 스스로 모순된다 —
		 * 숫자는 적다고 하고 문장은 많다고 한다.
		 *
		 * <p>그렇다고 추천을 접을 일은 아니다. 그 지역이 <b>열한 곳 중 위쪽 절반</b>이라는
		 * 사실은 그대로이므로, 양 대신 <b>덜 붐빈다</b>는 견주는 말로 옮긴다.
		 * 견주는 말은 기간이 어떻든 참이다.
		 */
		String quietness = manyQuiet ? "한적한 곳이 많은 편이에요" : "덜 붐비는 편이에요";
		if (interest == null || !interest.filtersRegions()) {
			return "다른 지역보다 " + quietness;
		}
		String noun = interest.noun();
		return "%s%s 많고, %s".formatted(noun, subjectParticle(noun), quietness);
	}

	/**
	 * 받침에 따라 <b>이/가</b>를 고른다.
	 *
	 * <p>⚠️ 하나로 박아 두면 분류마다 말이 깨진다 — "음식점가 많고"·"명소이 많고".
	 * 분류 이름은 {@link Interest#noun()}에 있고 앞으로도 늘 수 있어서, 자리마다 손으로
	 * 맞추는 대신 규칙으로 둔다.
	 *
	 * <p>한글 음절은 유니코드에서 <b>초성·중성·종성 순서로 배열</b>되어 있어, 시작점부터의
	 * 거리를 종성 개수(28)로 나눈 나머지가 0이면 받침이 없다. 한글이 아닌 글자로 끝나면
	 * (분류 이름이 영문·기호로 끝날 일은 없지만) 받침 없는 쪽으로 둔다.
	 */
	private static String subjectParticle(String word) {
		char last = word.charAt(word.length() - 1);
		if (last < '가' || last > '힣') {
			return "가";
		}
		return (last - '가') % 28 == 0 ? "가" : "이";
	}
}
