package com.peakoff.chat.domain;

/**
 * 카드 문장을 누가 썼는가.
 *
 * <h3>왜 남기는가</h3>
 * 화면은 이 값을 <b>보여주지 않는다</b> — 사용자에게는 그냥 한 줄이고, 누가 썼는지는
 * 알 필요가 없다. 우리가 알아야 한다: LLM 문장이 실제로 얼마나 쓰이는지,
 * 검증에 걸려 템플릿으로 되돌아가는 일이 잦은지.
 *
 * <p>그 비율이 낮으면 LLM ②는 <b>크레딧만 쓰고 아무 일도 안 하는 것</b>이므로 꺼야 한다.
 * 값이 없으면 그 판단을 할 근거가 없다.
 */
public enum CardLineSource {

	/** LLM이 쓰고 검증을 통과했다. */
	LLM,

	/** 서버가 만들었다. LLM이 꺼져 있거나 · 실패했거나 · 검증에 걸렸다. */
	TEMPLATE
}
