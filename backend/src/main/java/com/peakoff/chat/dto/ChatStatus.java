package com.peakoff.chat.dto;

/**
 * 챗봇이 답한 방식. <b>화면은 이 값으로 갈라 그린다.</b>
 *
 * <h3>왜 오류가 아니라 상태인가</h3>
 * 셋 다 <b>200으로 나간다.</b> 챗봇이 쉬는 것은 고장이 아니고, 무엇보다
 * 화면 한 칸이 빨갛게 죽으면 <b>완성도에서 크게 손해</b>다(CLAUDE.md).
 * 오류로 내려보내면 화면이 그것을 오류로 그리게 된다.
 */
public enum ChatStatus {

	/** 지역을 골랐다. 카드가 들어 있다. */
	OK,

	/** 여행지를 고르는 질문이 아니다. 정중히 물러난다. */
	OFF_TOPIC,

	/**
	 * 예측이 닿지 않는 <b>먼 훗날</b>을 물었다 ("내년 여름", "두 달 뒤").
	 *
	 * <h3>왜 따로 두는가</h3>
	 * {@link #UNAVAILABLE}과 달리 <b>사용자가 할 수 있는 일이 다르다.</b> 이쪽은
	 * 설문으로 가라고 할 자리가 아니라 <b>기간을 당겨 다시 물으면 되는</b> 자리다.
	 * 화면이 다르게 말해야 하므로 상태를 가른다.
	 *
	 * <p>⚠️ <b>잘못이 아니라 "지금은 아직"이다.</b> 창 밖 날짜로 코스를 짜도 막지 않고
	 * 칸마다 "아직 예측이 나오지 않은 날짜예요"라고만 하는 것과 같은 태도다 —
	 * 여행은 원래 미리 계획하고, 미리 묻는 사람을 나무랄 이유가 없다.
	 */
	TOO_FAR,

	/**
	 * 지금은 답할 수 없다. 인증키 없음 · 하루 상한 · 시간 초과 · 예측 자료 없음이 모두 여기다.
	 *
	 * <p><b>이유를 가르지 않는다.</b> 사용자가 할 수 있는 일이 어느 경우나 같기 때문이다 —
	 * 기존 설문으로 가면 된다. 이유는 서버 로그에 있다.
	 */
	UNAVAILABLE
}
