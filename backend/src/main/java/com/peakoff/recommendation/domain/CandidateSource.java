package com.peakoff.recommendation.domain;

/**
 * 대안 후보를 <b>어디서 가져왔는가.</b>
 *
 * <h2>왜 출처를 들고 다니는가</h2>
 * 추천 근거로 할 수 있는 말이 달라지기 때문이다. 연관 관광지에서 온 후보에게는
 * "함께 많이 찾는 곳"이라고 말할 수 있지만, 지역 카탈로그에서 고른 후보에게 같은 말을 하면
 * <b>계산하지 않은 것을 근거로 말하게 된다.</b>
 *
 * <p>출처를 안 들고 다니면 문구를 한 가지로 맞춰야 하는데, 그러면 연관 데이터를 쓰고도
 * 그 사실을 말하지 못하거나(설명력 손해), 쓰지 않고도 썼다고 말하게 된다(거짓).
 *
 * <h2>목록 하나에는 출처가 하나다</h2>
 * 두 출처를 한 Pool에 섞어 경쟁시키지 않는다. 섞으면 같은 목록 안에서 어떤 줄은
 * "함께 많이 찾는 곳"이고 어떤 줄은 아니게 되어, 사용자가 그 차이를 읽어낼 방법이 없다.
 * 연관 후보가 하나라도 있으면 연관만 쓰고, 하나도 없을 때만 지역으로 넘어간다.
 */
public enum CandidateSource {

	/**
	 * 연관 관광지 — <b>그 장소 방문객이 실제로 함께 많이 간 곳.</b>
	 *
	 * <p>맥락이 보존되는 대신 자주 빈다. 연관 이름이 우리 카탈로그로 이어지고, 분류가 맞고,
	 * 15km 안이고, 혼잡 자료가 있고, 5점 이상 한적해야 남는다 — 실측에서 관광지 넷 중
	 * 셋은 이 경로만으로는 대안을 얻지 못했다(경주 25.6%, 제주시 30.9%, 서귀포 33.7%).
	 */
	RELATED,

	/**
	 * 같은 지역 카탈로그 — <b>연관 후보가 하나도 남지 않았을 때만</b> 쓴다.
	 *
	 * <p>맥락은 약하지만 나머지 조건(지역·분류·거리·한적도)은 똑같이 지킨다.
	 * 이 경로를 열면서 대안이 있는 자리가 경주 20→58곳, 제주시 68→192곳,
	 * 서귀포 61→159곳이 됐다.
	 *
	 * <p>⚠️ 화면에는 <b>기술 용어를 쓰지 않는다.</b> "fallback"이 아니라
	 * "같은 지역에서 조건이 비슷한 곳"이라고 말한다 — 사용자에게는 우리 내부 사정이
	 * 아니라 그 장소가 왜 나왔는지가 필요하다.
	 */
	REGIONAL_FALLBACK;

	/**
	 * <b>후보를 어떻게 골랐는지</b>를 사람이 읽는 한 문장으로.
	 *
	 * <h3>왜 이 문장이 필요한가</h3>
	 * {@code CLAUDE.md}는 추천도를 {@code 한적도 + 연관성 + 카테고리 적합성 + 근접도}로
	 * 정의하는데 실제 점수 항목은 <b>한적도와 근접도 둘뿐</b>이다. 화면의 구성 내역을 펼치면
	 * 항목이 둘만 서서, 명세와 나란히 놓으면 <b>한 항목이 빠진 것처럼 보인다.</b>
	 *
	 * <p>빠진 것이 아니라 <b>다른 층에서 쓰고 있다.</b> 연관 관광지는 점수를 올리는 값이 아니라
	 * <b>후보를 고르는 문</b>이다 — 아무도 함께 가지 않는 곳은 애초에 그 목록에 없으므로,
	 * 가점 없이도 "너무 무명은 아니다"가 보장된다. 이 문장이 그 사실을 화면에서 말한다.
	 *
	 * <h3>⚠️ 왜 점수 항목으로 넣지 않았나 (2026-08-31 실측)</h3>
	 * 넣으려고 재봤더니 <b>연관 순위와 한적도가 음의 상관</b>이었다 —
	 * 6개 지역 26,819쌍에서 켄달 타우 {@code -0.073}, 6곳 중 5곳이 음수다
	 * (서귀포 -0.139 · 경주 -0.127). <b>함께 많이 가는 곳일수록 더 붐빈다.</b>
	 * 당연한 결과다. 연관 관광지는 곧 인기도이고 인기 = 붐빔이다.
	 *
	 * <p>여기에 가점을 주면 "더 붐비는 곳을 더 밀어라"가 되어 과제와 정면으로 어긋난다.
	 * 음의 상관이 <b>가장 강한 곳이 하필 경주·서귀포</b>라 더 그렇다.
	 *
	 * <h3>문장을 서버가 만드는 이유</h3>
	 * 출처에 따라 <b>할 수 있는 말이 다르고</b>, 그 판단은 서버가 한다.
	 * 화면이 {@code source} 값을 보고 문장을 조립하면, 출처가 하나 늘 때 서버와 화면을
	 * 함께 고쳐야 하고 한쪽을 놓치면 <b>계산하지 않은 것을 근거로 말하게 된다.</b>
	 * {@code PlaceOffStatus}가 문구를 들고 있는 것과 같은 이유다.
	 *
	 * <p>기술 용어는 쓰지 않는다. 사용자에게 필요한 것은 "fallback"이 아니라
	 * 그 후보들이 어디서 왔는지다.
	 *
	 * @param originName 기준 장소 이름. <b>조사를 붙이지 않는다</b> — 한국어의 "와/과"는
	 *                   앞 글자 받침에 따라 갈리는데 장소 이름이 무엇으로 끝날지 알 수 없다
	 *                   (실제로 "경주엑스포대공원와"가 나왔다)
	 */
	public String noteFor(String originName) {
		return switch (this) {
			case RELATED -> "%s에 다녀간 사람들이 함께 찾은 곳 중에서 골랐어요.".formatted(originName);
			case REGIONAL_FALLBACK ->
				"%s 근처에서 분류가 비슷한 곳 중에서 골랐어요.".formatted(originName);
		};
	}
}
