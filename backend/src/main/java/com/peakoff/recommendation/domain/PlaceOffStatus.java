package com.peakoff.recommendation.domain;

/**
 * 장소 교체 추천의 결과 상태.
 *
 * <h2>왜 빈 목록으로 두지 않는가</h2>
 * 개선폭 하한({@link AlternativeStandard#MIN_QUIETNESS_GAIN})이 생기면서 <b>목록이 비는 일이
 * 흔해졌다.</b> 실측에서 대안이 있던 자리의 36~51%가 빈 목록이 된다.
 *
 * <p>그런데 비는 이유가 서로 완전히 다르다. 원래 장소가 이미 한적해서 더 나은 곳이 없는
 * 것과, 대신할 만한 곳을 아예 못 찾은 것은 <b>사용자에게 정반대의 소식</b>이다.
 * 하나는 "잘 골랐다"이고 하나는 "우리가 못 찾았다"인데, 같은 빈 화면으로 뭉개면
 * 둘 다 "이 서비스는 데이터가 부실하다"로 읽힌다.
 *
 * <p>날짜 대안이 같은 상황을 이미 이렇게 다룬다({@code TimeOffStatus}). 두 회피 경로가
 * 같은 모양으로 답해야 화면도 같은 방식으로 말할 수 있다.
 *
 * <h2>왜 서버가 문구를 들고 있는가</h2>
 * 임계값을 서버에 두는 것과 같은 이유다. 판단의 근거와 그 판단을 설명하는 말이 갈라지면
 * 한쪽만 바뀐다. 하한을 3점으로 낮추는 날 문구도 함께 손봐야 하는데,
 * 문구가 화면에 있으면 그 사실을 아무도 모른다.
 */
public enum PlaceOffStatus {

	/** 권할 만한 후보를 찾았다. <b>문구가 없다</b> — 목록 자체가 답이다. */
	RECOMMENDED(null),

	/**
	 * 원래 장소가 이미 한적하다. 그래서 더 나은 곳을 찾지 못했다.
	 *
	 * <p><b>이것은 실패가 아니라 성공이다.</b> 사용자가 고른 자리가 이미 좋다는 뜻이라,
	 * "찾지 못했어요"라고 말하면 잘 고른 사람에게 서비스가 못했다고 사과하는 꼴이 된다.
	 *
	 * <p>{@link #NO_MEANINGFUL_IMPROVEMENT}와 사실은 같다(하한을 넘는 후보가 없다).
	 * 갈라 두는 이유는 <b>할 말이 다르기 때문</b>이다.
	 */
	ALREADY_QUIET("여기는 이미 한적한 편이에요.\n굳이 바꾸지 않아도 좋아요."),

	/** 후보는 있었지만 지금보다 뚜렷하게 한적한 곳이 없다. */
	NO_MEANINGFUL_IMPROVEMENT("지금보다 눈에 띄게 한적한 곳을 찾지 못했어요."),

	/**
	 * 자격을 따져 볼 후보 자체가 없었다.
	 *
	 * <p>같은 분류가 지역에 없거나, 있어도 혼잡 예측이 없는 곳뿐일 때다.
	 * 위의 둘과 달리 <b>개선폭까지 가 보지도 못했다.</b>
	 */
	NO_VALID_CANDIDATE("이 자리를 대신할 만한 곳을 찾지 못했어요."),

	/**
	 * 원래 장소의 한적도를 모른다.
	 *
	 * <p>얼마나 나아지는지를 재려면 기준이 있어야 하는데 그 기준이 없다. 음식점·숙박처럼
	 * 예측 대상이 아닌 장소가 여기 온다 — 그런 자리는 추천이 아니라
	 * "같은 분류·가까운 순"이라는 다른 경로로 안내한다({@code GET /places/{id}/nearby}).
	 */
	ORIGIN_NOT_FORECASTED("예상 혼잡을 알 수 없는 곳이라 추천 순서를 매기지 못해요.");

	private final String message;

	PlaceOffStatus(String message) {
		this.message = message;
	}

	/** 화면에 그대로 띄울 수 있는 문구. <b>할 말이 없으면 {@code null}이다.</b> */
	public String message() {
		return message;
	}
}
