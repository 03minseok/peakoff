package com.peakoff.place.domain;

import java.util.List;
import java.util.Optional;

/**
 * 관광지 목록을 공급한다.
 *
 * <p>이 인터페이스가 <b>교체 지점</b>이다. 목업 구현과 공공데이터 구현이 같은 모양을 지킨다.
 * 이걸 쓰는 쪽(서비스·컨트롤러)은 어느 구현이 붙었는지 알 필요가 없다.
 *
 * <h3>왜 "지역 전체 목록"이 없는가</h3>
 * 예전에는 {@code findByRegion}으로 지역의 모든 장소를 돌려줬다. 경주만 621곳이고
 * 지역이 늘면 수천 곳이 된다 — <b>화면에 늘어놓을 수 있는 양이 아니다.</b>
 * 그래서 장소는 검색으로 찾고, 검색 전에는 대표 관광지를 보여준다.
 *
 * <p>서버가 지역 자료를 통째로 캐시하는 것과는 다른 이야기다. 그건 빠르게 답하기 위한
 * 내부 사정이고, 이 인터페이스는 <b>화면이 감당할 수 있는 모양</b>으로만 답한다.
 */
public interface PlaceProvider {

	/**
	 * 이름에 검색어가 든 장소를 찾는다. 검색 범위는 그 지역 안으로 제한된다.
	 *
	 * @param limit 최대 개수. 화면이 한 번에 보여줄 만큼만
	 * @return 없으면 빈 목록. 검색은 "못 찾음"이 정상적인 결과다
	 */
	List<Place> search(Region region, String keyword, int limit);

	/**
	 * 지역을 대표하는 관광지를 <b>대표성 순으로</b> 돌려준다.
	 *
	 * <p>검색어를 아직 안 친 화면에 보여줄 목록이다. 빈 검색창만 두면 그 지역을 모르는
	 * 사용자는 첫 글자를 치지 못한다.
	 *
	 * <p>⚠️ 이 순서는 <b>인기 순</b>이지 추천 순이 아니다. 인기 장소는 붐비는 장소이므로
	 * 추천 점수에 가점으로 쓰면 오버투어리즘 과제와 어긋난다. 목록을 늘어놓는 순서로만 쓴다.
	 */
	List<Place> representatives(Region region, int limit);

	Optional<Place> findById(String placeId);

	/**
	 * 이 장소가 <b>어느 지역의 것인가</b>. 못 찾으면 빈 값.
	 *
	 * <h3>왜 필요한가</h3>
	 * 장소 ID에는 지역이 묻어 있지 않은데, <b>지역이 코스의 단위</b>다 — 찜해 둔 곳으로
	 * 여행을 시작하려면 어느 지역으로 조건 화면을 열지 알아야 한다.
	 *
	 * <p>{@link #findById}가 이미 지역을 하나씩 훑으면서 <b>어느 카탈로그에서 찾았는지를
	 * 버리고 있다.</b> 부르는 쪽이 그 일을 다시 하게 두면 같은 순회가 두 번 돈다.
	 */
	Optional<SupportedRegion> regionOf(String placeId);

	/**
	 * 기준 장소 근처의 <b>같은 분류</b> 장소들. 가까운 순.
	 *
	 * <p>지역을 받지 않는 것은 {@link #findById}와 같은 이유다 — 장소 ID만으로는 지역을 알 수 없어
	 * 구현이 각자 자기 지역을 안다. v1은 파일럿 한 지역이다.
	 *
	 * <p>⚠️ <b>점수가 없다.</b> 한적도를 모르는 장소(음식점·숙박)를 위한 것이라
	 * 추천도를 매길 수 없다. 거리와 분류라는 사실만 전한다({@link NearbyPlace} 참고).
	 *
	 * @return 없으면 빈 목록. 반경 밖에 있거나 같은 분류가 없으면 그렇다
	 */
	List<NearbyPlace> nearby(Place origin, int limit);

	/**
	 * 장소 하나의 <b>읽을거리</b>(주소·소개글).
	 *
	 * <p>{@link #findById}와 갈라 둔 이유는 <b>값이 오는 곳이 다르기 때문</b>이다.
	 * 이름·좌표·분류·사진은 지역 카탈로그에 이미 있지만, 소개글은 상세 조회에만 있어
	 * 장소마다 공사를 한 번씩 불러야 한다. 한 메서드로 합치면 목록을 그릴 때마다
	 * 그 호출이 함께 나가게 된다.
	 *
	 * <p>⚠️ <b>화면이 펼칠 때만 부른다.</b> 목록에 붙이면 N곳 = N번이 되고,
	 * 그것이 2026-08-26 한도 소진 사고의 모양이었다.
	 *
	 * @return 그런 장소가 없거나 조회가 막혔으면 빈 값
	 */
	Optional<PlaceDescription> describe(String placeId);
}
